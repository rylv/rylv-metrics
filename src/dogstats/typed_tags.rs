//! Compile-time ordered tag sets.

use crate::{RylvStr, RylvTag};

mod private {
    pub trait Sealed {}

    impl Sealed for super::RylvStr<'_> {}
    impl Sealed for Option<super::RylvStr<'_>> {}
}

/// Conversion used by the derive macro for required and optional tag values.
#[doc(hidden)]
pub trait TagValue: private::Sealed {
    /// Whether this value can omit its tag.
    const OPTIONAL: bool;

    /// Creates a tag, preserving static strings and omitting absent values.
    fn optional_tag(&self, key: &'static str) -> Option<RylvTag<'_>>;

    /// Creates a tag on the statically selected path for required fields.
    fn required_tag(&self, key: &'static str) -> RylvTag<'_>;
}

impl TagValue for RylvStr<'_> {
    const OPTIONAL: bool = false;

    #[inline]
    fn optional_tag(&self, key: &'static str) -> Option<RylvTag<'_>> {
        Some(self.required_tag(key))
    }

    #[inline]
    fn required_tag(&self, key: &'static str) -> RylvTag<'_> {
        let value = match self {
            Self::Static(value) => RylvStr::Static(value),
            _ => RylvStr::Borrowed(self.as_ref()),
        };
        RylvTag::Compound(RylvStr::Static(key), value)
    }
}

impl TagValue for Option<RylvStr<'_>> {
    const OPTIONAL: bool = true;

    #[inline]
    fn optional_tag(&self, key: &'static str) -> Option<RylvTag<'_>> {
        self.as_ref().map(|value| value.required_tag(key))
    }

    #[inline]
    fn required_tag(&self, key: &'static str) -> RylvTag<'_> {
        // OPTIONAL is true, so the derive never selects this path for Option.
        self.optional_tag(key)
            .unwrap_or(RylvTag::Full(RylvStr::Static("")))
    }
}

/// A set of tags supplied in canonical order to `*_typed` collector methods.
///
/// Prefer `#[derive(RylvTags)]`, which enforces these rules for structs with
/// `RylvStr` or `Option<RylvStr>` fields. `None` omits a tag. Manual
/// implementations must uphold the following contract
/// on every call to [`RylvTags::sorted_tags`]:
///
/// - Return a guard containing the complete tag slice. Borrowed values must
///   remain valid for the lifetime of the guard.
/// - Each tag must represent a `key:value` pair with a nonempty, unique key.
///   Keys must not contain `:`, `,`, `|`, `#`, or whitespace. Values may be
///   empty and may contain `:`.
/// - Sort the tags in ascending [`RylvTag::cmp`] order by their complete
///   resolved `key:value` form. Field declaration order or sorting by value
///   alone is insufficient.
///
/// The typed collector paths trust this ordering and do not sort or validate
/// the slice. Breaking the contract can split one metric into multiple
/// aggregation series.
///
/// ```
/// # #[cfg(all(feature = "derive", feature = "shared-collector"))] {
/// use rylv_metrics::{MetricCollectorTrait, RylvStr, RylvTags, SharedCollector};
/// #[derive(RylvTags)]
/// struct Tags<'a> { env: RylvStr<'a> }
/// let collector = SharedCollector::default();
/// collector.count_typed(RylvStr::from_static("requests"), &Tags { env: RylvStr::from_static("prod") });
/// # }
/// ```
pub trait RylvTags {
    /// The owned tag array or other guard returned by [`Self::sorted_tags`].
    type Guard<'a>: AsRef<[RylvTag<'a>]> + AsMut<[RylvTag<'a>]>
    where
        Self: 'a;

    /// Returns tags according to the trait contract above.
    fn sorted_tags(&self) -> Self::Guard<'_>;
}

/// A stack-allocated tag array generated by `#[derive(RylvTags)]`.
pub struct RylvTagsGuard<'a, const N: usize> {
    tags: [RylvTag<'a>; N],
    len: usize,
}

impl<'a, const N: usize> RylvTagsGuard<'a, N> {
    /// Wraps a canonically sorted array of tags.
    ///
    /// The caller must uphold the [`RylvTags`] ordering and key requirements.
    #[inline]
    #[must_use]
    pub const fn new(tags: [RylvTag<'a>; N]) -> Self {
        Self { tags, len: N }
    }

    /// Builds a guard from canonically ordered optional tags, omitting `None` values.
    ///
    /// The caller must uphold the [`RylvTags`] ordering and key requirements
    /// for all present tags.
    #[inline]
    #[must_use]
    pub fn from_optional(tags: [Option<RylvTag<'a>>; N]) -> Self {
        let mut present = tags.into_iter().flatten();
        let mut len = 0;
        let tags = std::array::from_fn(|_| {
            present.next().map_or_else(
                || RylvTag::Full(RylvStr::Static("")),
                |tag| {
                    len += 1;
                    tag
                },
            )
        });
        Self { tags, len }
    }
}

impl<'a, const N: usize> AsRef<[RylvTag<'a>]> for RylvTagsGuard<'a, N> {
    #[inline]
    fn as_ref(&self) -> &[RylvTag<'a>] {
        &self.tags[..self.len]
    }
}

impl<'a, const N: usize> AsMut<[RylvTag<'a>]> for RylvTagsGuard<'a, N> {
    #[inline]
    fn as_mut(&mut self) -> &mut [RylvTag<'a>] {
        &mut self.tags[..self.len]
    }
}
